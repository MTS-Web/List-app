fun generateLightColorScheme(seed: Color): ColorScheme {
    return lightColorScheme(
        primary = seed,
        onPrimary = if (seed.luminance() > 0.5f) Color.Black else Color.White,
        primaryContainer = seed.copy(alpha = 0.2f),
        onPrimaryContainer = seed,
        secondary = seed.copy(red = seed.red * 0.8f, green = seed.green * 0.8f, blue = seed.blue * 0.8f),
        onSecondary = Color.White,
        secondaryContainer = seed.copy(alpha = 0.15f),
        onSecondaryContainer = seed,
        background = Color(0xFFFAFAFA),
        onBackground = Color(0xFF1C1B1F),
        surface = Color(0xFFFAFAFA),
        onSurface = Color(0xFF1C1B1F),
        surfaceVariant = Color(0xFFE7E0EC),
        onSurfaceVariant = Color(0xFF49454F),
        outline = Color(0xFF79747E)
    )
}

fun generateDarkColorScheme(seed: Color): ColorScheme {
    val brighterSeed = Color(
        red = minOf(1f, seed.red * 1.2f),
        green = minOf(1f, seed.green * 1.2f),
        blue = minOf(1f, seed.blue * 1.2f),
        alpha = seed.alpha
    )
    return darkColorScheme(
        primary = brighterSeed,
        onPrimary = Color.Black,
        primaryContainer = brighterSeed.copy(alpha = 0.3f),
        onPrimaryContainer = brighterSeed,
        secondary = brighterSeed.copy(red = brighterSeed.red * 0.9f, green = brighterSeed.green * 0.9f, blue = brighterSeed.blue * 0.9f),
        onSecondary = Color.Black,
        secondaryContainer = brighterSeed.copy(alpha = 0.25f),
        onSecondaryContainer = brighterSeed,
        background = Color(0xFF1C1B1F),
        onBackground = Color(0xFFE6E1E5),
        surface = Color(0xFF1C1B1F),
        onSurface = Color(0xFFE6E1E5),
        surfaceVariant = Color(0xFF49454F),
        onSurfaceVariant = Color(0xFFCAC4D0),
        outline = Color(0xFF938F99)
    )
}
